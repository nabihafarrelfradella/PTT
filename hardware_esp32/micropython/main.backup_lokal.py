def lcd_show(line1, line2=""):
    print(f"[LCD] {line1} | {line2}")
    if lcd:
        try:
            # Update baris 1 & 2 langsung tanpa lcd.clear() agar tidak kedip/flicker
            l1 = (str(line1) + "                ")[:16]
            l2 = (str(line2) + "                ")[:16]
            lcd.move_to(0, 0)
            lcd.putstr(l1)
            lcd.move_to(0, 1)
            lcd.putstr(l2)
        except Exception:
            pass

