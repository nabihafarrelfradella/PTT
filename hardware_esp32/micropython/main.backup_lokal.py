    print(f"[WiFi] Menghubungkan ke {ssid}...")
    
    # Trigger koneksi ke WiFi
    try:
        wlan.disconnect()
        time.sleep_ms(100)
    except:
        pass
    wlan.connect(ssid, password)
    
    # Animasi titik berurutan di Baris 1: Connect WiFi. -> Connect WiFi.. -> Connect WiFi...
    dots = [".   ", "..  ", "... ", "    "]
    
    # Cek setiap 350ms sampai connect (maksimal 12 detik)
    for i in range(35):
        if wlan.isconnected():
            return True
        
        dot_str = dots[i % len(dots)]
        # Baris 1: Connect WiFi... | Baris 2: Nama WiFi (misal Farrel)
        lcd_show(f"Connect WiFi{dot_str}", ssid[:16])
        time.sleep_ms(350)
        
    return False

